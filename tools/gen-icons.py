#!/usr/bin/env python3
"""Gerador de ícones vetoriais do APK Tester ("Behemoth").

Fase: A0/A1 — geradores core. Produz os 500+ vector drawables do flagship
(24x24, paths M/L/C/Z com pontos arredondados a 0.5), o conjunto adaptive
icon (foreground/background/monochrome p/ API 33), os mipmaps legacy+round
por densidade, o banner de TV 320x180 e as 8 configurações de activity-alias
(ic_launcher_r1..r8). Tudo determinístico por --seed; só stdlib python3.

Também grava icons-index.json (id -> sha256) e manifest.json com o sha256 de
cada artefato (sem timestamps, para saída reprodutível byte a byte).

Uso:
    python3 tools/gen-icons.py --out /tmp/out [--seed 20261022]
    python3 tools/gen-icons.py --selftest
"""

import argparse
import hashlib
import json
import random
import re
import sys
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

DEFAULT_SEED = 20261022
NS = "http://schemas.android.com/apk/res/android"
VECTOR_COUNT = 600          # ic_vector_0001..600 (IconGrid usa os 600)
ALIAS_COUNT = 8             # ic_launcher_r1..r8 + res/xml/activity_alias_rN.xml
DENSITIES = ["mdpi", "hdpi", "xhdpi", "xxhdpi", "xxxhdpi"]
PALETTE = [
    "#FF3366CC", "#FFCC3366", "#FF33CC66", "#FF6633CC", "#FFCC6633",
    "#FF336666", "#FF66CC33", "#FF333333", "#FF888888", "#FFCC3300",
    "#FF006699", "#FF990066",
]
PATH_TOKEN_RE = re.compile(r"^[MLCZ0-9., ]+$")

ADAPTIVE_TMPL = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/gen-icons.py seed={seed} - deterministic fixture -->
<adaptive-icon xmlns:android="{ns}">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
"""

LAYER_LIST_TMPL = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/gen-icons.py seed={seed} - {kind} @ {density} -->
<layer-list xmlns:android="{ns}">
    <item android:drawable="@drawable/ic_launcher_background" />
    <item android:drawable="@drawable/ic_launcher_foreground" />
</layer-list>
"""

ALIAS_TMPL = """<?xml version="1.0" encoding="utf-8"?>
<!-- activity-alias r{n}: o <activity-alias> real entra no manifesto (fase A1) -->
<activity-alias-config>
    <alias
        name="dev.apktester.behemoth.LauncherR{n}"
        targetActivity="dev.apktester.behemoth.MainActivity"
        icon="@drawable/ic_launcher_r{n}"
        roundIcon="@mipmap/ic_launcher_round" />
</activity-alias-config>
"""


def fmt(value: float) -> str:
    """Formata coordenada: inteiros sem casa decimal, 0.5 steps com uma."""
    if float(value).is_integer():
        return str(int(value))
    return str(value)


def coord(rng: random.Random, lo: float, hi: float) -> float:
    """Coordenada pseudo-aleatória em passos de 0.5 dentro de [lo, hi]."""
    return rng.randrange(int(lo * 2), int(hi * 2) + 1) / 2.0


def gen_path_data(rng: random.Random, lo: float = 1.0, hi: float = 23.0) -> str:
    """Path data válido: M seguido de 2-5 segmentos L/C, fechado com Z."""
    x, y = coord(rng, lo, hi), coord(rng, lo, hi)
    parts = [f"M{fmt(x)},{fmt(y)}"]
    for _ in range(rng.randint(2, 5)):
        if rng.random() < 0.55:
            parts.append(f"L{fmt(coord(rng, lo, hi))},{fmt(coord(rng, lo, hi))}")
        else:
            pts = [f"{fmt(coord(rng, lo, hi))},{fmt(coord(rng, lo, hi))}"
                   for _ in range(3)]
            parts.append("C" + " ".join(pts))
    parts.append("Z")
    return " ".join(parts)


def make_paths(rng: random.Random, count: int, lo: float, hi: float) -> list:
    """Lista de dicts {fill, data, stroke?, strokeWidth?} prontos p/ XML."""
    paths = []
    for _ in range(count):
        entry = {
            "fill": rng.choice(PALETTE),
            "data": gen_path_data(rng, lo, hi),
        }
        if rng.random() < 0.25:
            entry["stroke"] = rng.choice(PALETTE)
            entry["strokeWidth"] = fmt(rng.randrange(1, 7) / 2.0)
        paths.append(entry)
    return paths


def vector_xml(width: int, height: int, paths: list, comment: str) -> str:
    """Serializa um <vector> Android com paths M/L/C/Z e cores da paleta."""
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        f"<!-- {comment} -->",
        f'<vector xmlns:android="{NS}"',
        f'    android:width="{width}dp"',
        f'    android:height="{height}dp"',
        f'    android:viewportWidth="{width}"',
        f'    android:viewportHeight="{height}">',
    ]
    for path in paths:
        lines.append("    <path")
        lines.append(f'        android:fillColor="{path["fill"]}"')
        if "stroke" in path:
            lines.append(f'        android:strokeColor="{path["stroke"]}"')
            lines.append(f'        android:strokeWidth="{path["strokeWidth"]}"')
            lines.append('        android:strokeLineCap="round"')
        lines.append(f'        android:pathData="{path["data"]}" />')
    lines.append("</vector>")
    lines.append("")
    return "\n".join(lines)


def write_manifest(out_dir: Path, tool: str, seed: int, rel_paths: list) -> None:
    entries = []
    for rel in sorted(rel_paths):
        data = (out_dir / rel).read_bytes()
        entries.append({
            "path": rel,
            "bytes": len(data),
            "sha256": hashlib.sha256(data).hexdigest(),
        })
    payload = {"tool": tool, "seed": seed, "artifacts": entries}
    (out_dir / "manifest.json").write_text(
        json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def generate(out_dir: Path, seed: int) -> list:
    """Gera toda a árvore de ícones; devolve caminhos relativos gravados."""
    rng = random.Random(seed)
    artifacts = []
    index = {}

    def write(rel: str, text: str) -> None:
        path = out_dir / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        artifacts.append(rel)

    def write_icon(icon_id: str, rel: str, text: str) -> None:
        write(rel, text)
        index[icon_id] = hashlib.sha256(text.encode("utf-8")).hexdigest()

    # 1) 600 vector drawables 24x24 (fixture principal p/ IconGrid).
    for i in range(1, VECTOR_COUNT + 1):
        icon_id = f"ic_vector_{i:04d}"
        paths = make_paths(rng, rng.randint(1, 5), 1.0, 23.0)
        write_icon(icon_id, f"res/drawable/{icon_id}.xml",
                   vector_xml(24, 24, paths,
                              f"apk-tester icon {icon_id} seed={seed}"))

    # 2) Adaptive icon: background sólido + foreground/monochrome (zona segura).
    bg_paths = [{"fill": "#FF101820",
                 "data": "M0,0 L108,0 L108,108 L0,108 Z"}]
    bg_paths += make_paths(rng, 2, 4.0, 104.0)
    write_icon("ic_launcher_background", "res/drawable/ic_launcher_background.xml",
               vector_xml(108, 108, bg_paths,
                          f"adaptive background seed={seed}"))
    fg_paths = make_paths(rng, rng.randint(2, 4), 21.0, 87.0)
    write_icon("ic_launcher_foreground", "res/drawable/ic_launcher_foreground.xml",
               vector_xml(108, 108, fg_paths,
                          f"adaptive foreground (safe zone 66dp) seed={seed}"))
    mono_paths = make_paths(rng, rng.randint(1, 2), 21.0, 87.0)
    for path in mono_paths:
        path["fill"] = "#FFFFFFFF"
        path.pop("stroke", None)
    write_icon("ic_launcher_monochrome", "res/drawable/ic_launcher_monochrome.xml",
               vector_xml(108, 108, mono_paths,
                          f"adaptive monochrome (API 33) seed={seed}"))

    # 3) 8 ícones de launcher alias (ic_launcher_r1..r8).
    for i in range(1, ALIAS_COUNT + 1):
        icon_id = f"ic_launcher_r{i}"
        paths = make_paths(rng, rng.randint(2, 3), 1.0, 23.0)
        paths[0]["fill"] = PALETTE[i % len(PALETTE)]
        write_icon(icon_id, f"res/drawable/{icon_id}.xml",
                   vector_xml(24, 24, paths,
                              f"launcher alias r{i} seed={seed}"))

    # 4) TV banner placeholder 320x180 (vetor, sem texto).
    banner_paths = [{"fill": "#FF0B1322",
                     "data": "M0,0 L320,0 L320,180 L0,180 Z"}]
    banner_paths += make_paths(rng, rng.randint(3, 5), 4.0, 176.0)
    write_icon("tv_banner", "res/drawable/tv_banner.xml",
               vector_xml(320, 180, banner_paths,
                          f"TV banner placeholder 320x180 seed={seed}"))

    # 5) mipmap-anydpi-v26 (adaptive) + legacy/round por densidade.
    adaptive = ADAPTIVE_TMPL.format(seed=seed, ns=NS)
    write_icon("ic_launcher", "res/mipmap-anydpi-v26/ic_launcher.xml", adaptive)
    write_icon("ic_launcher_round", "res/mipmap-anydpi-v26/ic_launcher_round.xml",
               adaptive)
    for density in DENSITIES:
        legacy = LAYER_LIST_TMPL.format(seed=seed, kind="legacy", ns=NS,
                                        density=density)
        round_xml = LAYER_LIST_TMPL.format(seed=seed, kind="legacy-round",
                                           ns=NS, density=density)
        write_icon(f"ic_launcher_legacy_{density}",
                   f"res/mipmap-{density}/ic_launcher.xml", legacy)
        write_icon(f"ic_launcher_round_legacy_{density}",
                   f"res/mipmap-{density}/ic_launcher_round.xml", round_xml)

    # 6) 8 configs de activity-alias (o manifesto as consome na fase A1).
    for i in range(1, ALIAS_COUNT + 1):
        write(f"res/xml/activity_alias_r{i}.xml", ALIAS_TMPL.format(n=i))

    index_json = json.dumps(index, indent=2, sort_keys=True,
                            ensure_ascii=False) + "\n"
    write("icons-index.json", index_json)
    write_manifest(out_dir, "gen-icons.py", seed, artifacts)
    return artifacts


def run_selftest() -> int:
    """Gera em tempdir, parseia um drawable e valida estrutura/contagens."""
    try:
        with tempfile.TemporaryDirectory(prefix="apktester-gen-icons-") as tmp:
            root = Path(tmp)
            generate(root, DEFAULT_SEED)
            sample = ET.fromstring(
                (root / "res/drawable/ic_vector_0001.xml").read_text("utf-8"))
            assert sample.tag == "vector", f"root={sample.tag}"
            width = sample.attrib[f"{{{NS}}}viewportWidth"]
            height = sample.attrib[f"{{{NS}}}viewportHeight"]
            assert (width, height) == ("24", "24"), "viewport != 24x24"
            paths = sample.findall("path")
            assert 1 <= len(paths) <= 5, f"paths={len(paths)}"
            for path in paths:
                data = path.attrib[f"{{{NS}}}pathData"]
                assert data.startswith("M") and data.endswith("Z"), data
                assert PATH_TOKEN_RE.match(data), f"path inválido: {data}"
            adaptive = ET.fromstring(
                (root / "res/mipmap-anydpi-v26/ic_launcher.xml").read_text("utf-8"))
            assert adaptive.tag == "adaptive-icon", adaptive.tag
            assert len(adaptive.findall("monochrome")) == 1, "monochrome ausente"

            index = json.loads((root / "icons-index.json").read_text("utf-8"))
            vector_ids = [k for k in index if k.startswith("ic_vector_")]
            assert len(vector_ids) == VECTOR_COUNT, f"vetores={len(vector_ids)}"
            assert len(index) >= VECTOR_COUNT + 14, f"index={len(index)}"
            for i in range(1, ALIAS_COUNT + 1):
                assert f"ic_launcher_r{i}" in index, f"alias r{i} fora do index"
                assert (root / f"res/xml/activity_alias_r{i}.xml").exists()

            second = root / "second-run"
            generate(second, DEFAULT_SEED)
            rel = "res/drawable/ic_vector_0100.xml"
            a = hashlib.sha256((root / rel).read_bytes()).hexdigest()
            b = hashlib.sha256((second / rel).read_bytes()).hexdigest()
            assert a == b, "saída não determinística"
    except AssertionError as exc:
        print(f"gen-icons selftest: FAIL ({exc})")
        return 1
    print("gen-icons selftest: OK")
    return 0


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(
        description="Gera vector drawables, adaptive icons, mipmaps e banner TV.")
    parser.add_argument("--out", help="diretório de saída (obrigatório)")
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED)
    parser.add_argument("--selftest", action="store_true",
                        help="roda asserções internas e sai com 0/1")
    args = parser.parse_args(argv)
    if args.selftest:
        return run_selftest()
    if not args.out:
        parser.error("--out é obrigatório (ou use --selftest)")
    out_dir = Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)
    artifacts = generate(out_dir, args.seed)
    print(f"gen-icons: {len(artifacts)} artefatos gravados em {out_dir} "
          f"(seed={args.seed})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
