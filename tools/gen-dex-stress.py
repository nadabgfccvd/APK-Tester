#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""gen-dex-stress.py — Corpus-fonte Java de estresse DEX (APK Tester).

Gera o CORPUS-FONTE (o .dex real é empacotado depois por tools/fixture-pack.py
com aapt2+d8) para exercitar os limites de 16 bits do formato DEX:
(1) --classes (650) x --methods-per-class (101) métodos public void
Method_NNNNN numerados globalmente = 65.650 definições > 65.536 method_ids
(650x100 = 65.000 ficaria ABAIXO; por isso 101); (2) StringPoolStress.java,
--strings (10000) constantes longas e únicas semeadas por sílabas;
(3) InvokeCustomStress.java denso em lambdas (java.util.function) + method
references (invokedynamic); (4) FieldStress.java, --fields (4096) campos int.

Saída: <out>/java/dev/apktester/stress/*.java (layout AGP padrão) +
<out>/stress-plan.json + <out>/manifest.json (convenção, sem timestamps).
multidex_ways=8 é a meta de fatiamento do fixture-pack ("8-way multi-dex");
o d8 por si produziria ~2-3 classesN.dex. Java ASCII-only para javac.

Uso: python3 tools/gen-dex-stress.py --out DIR [--seed N] [--selftest]
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import random
import re
import shutil
import sys
import tempfile

DEFAULT_SEED = 20261022
TOOL = "gen-dex-stress.py"
PACKAGE = "dev.apktester.stress"
JAVA_DIR, PLAN_NAME = "java", "stress-plan.json"
METHOD_IDS_CEIL, MULTIDEX_WAYS, LAMBDA_COUNT = 65536, 8, 64
DEFAULT_CLASSES, DEFAULT_MPP = 650, 101  # 650 x 101 = 65.650 > 65.536
DEFAULT_STRINGS, DEFAULT_FIELDS = 10000, 4096
SPECIAL_CLASSES = ("StringPoolStress", "InvokeCustomStress", "FieldStress")
SYLLABLES = ("ka", "ro", "mi", "ta", "lu", "zen", "por", "vex", "qui", "nal",
             "dor", "sul", "fera", "gol", "ixa", "tum", "bras", "ond", "vel",
             "cro", "mur", "tep", "zar", "oli")# (interface, expressão lambda com {n}/{m}, uso com {i}/{n}) — call sites variados
LAMBDA_KINDS = (
    ("IntUnaryOperator", "x -> x + {n}", "acc = s_{i:03d}.applyAsInt(acc);"),
    ("IntPredicate", "x -> (x % {m}) == 0", "acc += s_{i:03d}.test(acc) ? 1 : 0;"),
    ("IntSupplier", "() -> {n}", "acc += s_{i:03d}.getAsInt();"),
    ("Supplier<Integer>", "() -> {n}", "acc += s_{i:03d}.get();"),
    ("Function<Integer, Integer>", "v -> v * {m}", "acc += s_{i:03d}.apply(acc);"),
    ("BiFunction<Integer, Integer, Integer>", "(a, b) -> a + b + {n}", "acc += s_{i:03d}.apply(acc, {n});"),
    ("Predicate<String>", "s -> s.length() < {m}", 'acc += s_{i:03d}.test("site{n}") ? 1 : 0;'),
    ("Consumer<Object>", 'v -> System.out.print("")', "s_{i:03d}.accept(this);"),
)
# (interface, method reference, uso) — method refs também viram invoke-custom
METHOD_REF_SITES = (
    ("IntUnaryOperator", "this::twice", "acc = m_000.applyAsInt(acc);"),
    ("ToIntFunction<String>", "String::length", 'acc += m_001.applyAsInt("apktester");'),
    ("IntPredicate", "this::positive", "acc += m_002.test(acc) ? 1 : 0;"),
    ("IntFunction<int[]>", "int[]::new", "acc += m_003.apply(8).length;"),
    ("Predicate<Object>", "Objects::isNull", "acc += m_004.test(null) ? 1 : 0;"),
    ("BiFunction<Integer, Integer, Integer>", "this::sum", "acc += m_005.apply(acc, 1);"),
    ("UnaryOperator<String>", "String::trim", 'acc += m_006.apply(" a ").length();'),
    ("Function<Integer, Integer>", "Integer::reverse", "acc += m_007.apply(acc);"),
)
INVOKE_IMPORTS = ("java.util.Objects", "java.util.function.BiFunction",
                  "java.util.function.Consumer", "java.util.function.Function",
                  "java.util.function.IntFunction", "java.util.function.IntPredicate",
                  "java.util.function.IntSupplier", "java.util.function.IntUnaryOperator",
                  "java.util.function.Predicate", "java.util.function.Supplier",
                  "java.util.function.ToIntFunction", "java.util.function.UnaryOperator")
def seed_from(base: int, label: str) -> int:
    """Sub-semente estável derivada de (base, rótulo) via SHA-256."""
    digest = hashlib.sha256(f"{base}:{label}".encode("utf-8")).digest()
    return int.from_bytes(digest[:8], "little")


def sha256_file(path: str) -> str:
    """SHA-256 em streaming."""
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def method_class_source(idx: int, mpp: int) -> str:
    """Fonte de UMA classe de estresse com mpp métodos void numerados globalmente."""
    cid, start = idx + 1, idx * mpp + 1
    lines = [f"package {PACKAGE};", "",
             f"/* Stress class {cid:05d} (generated by gen-dex-stress.py - do not edit). */",
             f"public final class Stress_{cid:05d} {{",
             f"    public int sink_{cid:05d};", ""]
    for k in range(mpp):
        lines += [f"    public void Method_{start + k:05d}() {{",
                  f"        sink_{cid:05d} += {k + 1};", "    }", ""]
    lines.append("}")
    return "\n".join(lines) + "\n"


def long_constant(rng: random.Random, used: set) -> str:
    """Constante String longa (>= 40 chars) e única; palavras por sílabas semeadas."""
    while True:
        parts, length = [], 0
        while length < 40:
            word = "".join(rng.choice(SYLLABLES) for _ in range(rng.randint(2, 8)))
            parts.append(word)
            length += len(word) + 1
        value = " ".join(parts)
        if value not in used:
            used.add(value)
            return value


def string_pool_source(rng: random.Random, count: int) -> str:
    """StringPoolStress: count constantes estáticas (caem no string_ids do DEX)."""
    used = set()
    lines = [f"package {PACKAGE};", "",
             "/* String pool stress: unique long constants (generated - do not edit). */",
             "public final class StringPoolStress {"]
    for i in range(count):
        lines.append(
            f'    public static final String S_{i:05d} = "{long_constant(rng, used)}";')
    lines += ["", "    public static String pick(int i) {",
              "        String base = (i & 1) == 0 ? S_00001 : S_00002;",
              "        return new StringBuilder(base).reverse().toString();",
              "    }", "}", ""]
    return "\n".join(lines)


def invoke_custom_source(lambdas: int = LAMBDA_COUNT) -> str:
    """InvokeCustomStress: lambdas + method refs (invokedynamic/call sites)."""
    lines = [f"package {PACKAGE};", ""]
    lines += [f"import {name};" for name in INVOKE_IMPORTS]
    lines += ["",
              "/* invoke-custom corpus: lambda-heavy (generated - do not edit). */",
              "public final class InvokeCustomStress {", "",
              "    private int twice(int v) { return v * 2; }", "",
              "    private boolean positive(int v) { return v > 0; }", "",
              "    private int sum(int a, int b) { return a + b; }", "",
              "    public int run(int seed) {", "        int acc = seed;"]
    for i in range(lambdas):
        iface, expr, use = LAMBDA_KINDS[i % len(LAMBDA_KINDS)]
        kw = {"i": i, "n": i + 1, "m": (i % 7) + 2}
        lines.append(f"        {iface} s_{i:03d} = {expr.format(**kw)}; {use.format(**kw)}")
    for i, (iface, ref, use) in enumerate(METHOD_REF_SITES):
        lines.append(f"        {iface} m_{i:03d} = {ref}; {use}")
    lines += ["        return acc;", "    }", "}", ""]
    return "\n".join(lines)


def field_stress_source(count: int) -> str:
    """FieldStress: count campos públicos int (pressão no pool field_ids)."""
    lines = [f"package {PACKAGE};", "",
             "/* Field id stress: public int fields (generated - do not edit). */",
             "public final class FieldStress {", "    private int acc;"]
    for i in range(count):
        lines.append(f"    public int Field_{i + 1:05d} = {i + 1};")
    lines += ["", "    public int touch(int seed) {",
              "        acc = seed + Field_00001 + Field_00002;",
              f"        return acc + Field_{count:05d};", "    }", "}", ""]
    return "\n".join(lines)


def build_plan(classes: int, mpp: int, strings: int, fields: int, seed: int) -> dict:
    """stress-plan.json — números que o .dex final (fixture-pack) deve cumprir."""
    defined = classes * mpp + 6  # 3 métodos públicos + 3 helpers das especiais
    ctors = classes + len(SPECIAL_CLASSES)  # cada <init> referencia Object.<init>
    refs = defined + ctors + classes + LAMBDA_COUNT * 3 + 4  # + libs (estimativa)
    return {"tool": TOOL, "seed": seed, "package": PACKAGE,
            "classes": classes, "methods_per_class": mpp,
            "expected_methods": classes * mpp, "expected_method_refs": refs,
            "expected_strings": strings, "expected_fields": fields,
            "expected_lambdas": LAMBDA_COUNT,
            "expected_method_ref_sites": len(METHOD_REF_SITES),
            "multidex_ways": MULTIDEX_WAYS,
            "notes": ("Corpus-fonte apenas: o .dex real e o fatiamento em 8 ways "
                      "sao produzidos por tools/fixture-pack.py (d8). "
                      "expected_method_refs = definicoes + construtores + refs "
                      "de biblioteca estimadas; as classes*mpp definicoes ja "
                      "excedem o teto de 65536 method_ids por si.")}


def write_file(out_dir: str, rel: str, content: str) -> None:
    """Escreve um arquivo com caminho relativo '/'-separado, LF e UTF-8."""
    full = os.path.join(out_dir, rel.replace("/", os.sep))
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(content)


def generate(out_dir: str, seed: int, classes: int, mpp: int,
             strings: int, fields: int) -> tuple:
    """Escreve o corpus java/ + stress-plan.json + manifest.json (convenção)."""
    pkg_rel = f"{JAVA_DIR}/{PACKAGE.replace('.', '/')}"
    rng = random.Random(seed_from(seed, "dex:string-pool"))
    files = [(f"{pkg_rel}/Stress_{i + 1:05d}.java", method_class_source(i, mpp))
             for i in range(classes)]
    files.append((f"{pkg_rel}/StringPoolStress.java", string_pool_source(rng, strings)))
    files.append((f"{pkg_rel}/InvokeCustomStress.java", invoke_custom_source()))
    files.append((f"{pkg_rel}/FieldStress.java", field_stress_source(fields)))
    plan = build_plan(classes, mpp, strings, fields, seed)
    files.append((PLAN_NAME, json.dumps(plan, indent=2, sort_keys=True) + "\n"))
    artifacts = []
    for rel, content in files:
        write_file(out_dir, rel, content)
        full = os.path.join(out_dir, rel.replace("/", os.sep))
        artifacts.append({"path": rel, "bytes": os.path.getsize(full),
                          "sha256": sha256_file(full)})
    manifest = {"tool": TOOL, "seed": seed,
                "artifacts": [{k: a[k] for k in ("path", "bytes", "sha256")}
                              for a in artifacts]}
    write_file(out_dir, "manifest.json",
               json.dumps(manifest, indent=2, sort_keys=True) + "\n")
    return plan, artifacts


def selftest() -> int:
    """Corpus default em /tmp: >= 65536 métodos, plano coerente, pools íntegros."""
    tmp = tempfile.mkdtemp(prefix="apktester-dex-")
    try:
        corpus = os.path.join(tmp, "corpus")
        generate(corpus, DEFAULT_SEED, DEFAULT_CLASSES, DEFAULT_MPP,
                 DEFAULT_STRINGS, DEFAULT_FIELDS)
        with open(os.path.join(corpus, PLAN_NAME), encoding="utf-8") as fh:
            plan = json.load(fh)
        pkg_dir = os.path.join(corpus, JAVA_DIR, *PACKAGE.split("."))

        def read(name: str) -> str:
            with open(os.path.join(pkg_dir, name), encoding="utf-8") as fh:
                return fh.read()

        names = [n for n in sorted(os.listdir(pkg_dir))
                 if n.startswith("Stress_") and n.endswith(".java")]
        total = sum(read(n).count("public void Method_") for n in names)
        values = re.findall(r'S_\d{5} = "([^"]*)"', read("StringPoolStress.java"))
        invoke, fields_src = read("InvokeCustomStress.java"), read("FieldStress.java")
        refs = build_plan(DEFAULT_CLASSES, DEFAULT_MPP, DEFAULT_STRINGS,
                          DEFAULT_FIELDS, DEFAULT_SEED)["expected_method_refs"]
        assert total >= METHOD_IDS_CEIL, \
            f"{total} métodos < {METHOD_IDS_CEIL} method_ids do DEX"
        assert len(names) == DEFAULT_CLASSES and \
            total == plan["expected_methods"], "plano: métodos/classes divergem"
        assert len(values) == len(set(values)) == plan["expected_strings"], \
            "plano: strings divergem ou duplicadas"
        assert invoke.count("->") == plan["expected_lambdas"], "plano: lambdas divergem"
        assert invoke.count("::") == plan["expected_method_ref_sites"], \
            "plano: method refs divergem"
        assert fields_src.count("public int Field_") == plan["expected_fields"], \
            "plano: campos divergem"
        assert plan["multidex_ways"] == MULTIDEX_WAYS and \
            plan["expected_method_refs"] == refs, "plano: multidex/refs divergem"
        print(f"[gen-dex-stress] selftest OK: {total} métodos (>= {METHOD_IDS_CEIL}), "
              f"{len(values)} strings únicas, {plan['expected_lambdas']} lambdas + "
              f"{plan['expected_method_ref_sites']} method refs, "
              f"{plan['expected_fields']} campos, plano coerente "
              f"(multidex_ways={plan['multidex_ways']})")
        return 0
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(
        description="Corpus-fonte Java de estresse DEX (APK Tester).")
    ap.add_argument("--out", help="diretório do corpus (cria <out>/java/...)")
    ap.add_argument("--seed", type=int, default=DEFAULT_SEED,
                    help=f"semente determinística (padrão: {DEFAULT_SEED})")
    ap.add_argument("--classes", type=int, default=DEFAULT_CLASSES,
                    help=f"classes de método (padrão: {DEFAULT_CLASSES})")
    ap.add_argument("--methods-per-class", type=int, default=DEFAULT_MPP,
                    help=f"métodos por classe (padrão: {DEFAULT_MPP}; 650x101 = 65650 > 65536)")
    ap.add_argument("--strings", type=int, default=DEFAULT_STRINGS,
                    help=f"constantes no pool de strings (padrão: {DEFAULT_STRINGS})")
    ap.add_argument("--fields", type=int, default=DEFAULT_FIELDS,
                    help=f"campos no FieldStress (padrão: {DEFAULT_FIELDS})")
    ap.add_argument("--selftest", action="store_true",
                    help="roda auto-validação em /tmp e sai")
    args = ap.parse_args(argv)
    if args.selftest:
        return selftest()
    if not args.out:
        ap.error("--out é obrigatório (ou use --selftest)")
    if not (1 <= args.classes <= 20000 and 1 <= args.methods_per_class <= 2000
            and 3 <= args.strings <= 100000 and 2 <= args.fields <= 60000
            and args.classes * args.methods_per_class <= 2000000):
        ap.error("fora da faixa: classes [1,20000] x métodos [1,2000] (<= 2M), "
                 "strings [3,100000], fields [2,60000]")
    if args.classes * args.methods_per_class < METHOD_IDS_CEIL:
        print(f"[gen-dex-stress] AVISO: {args.classes}x{args.methods_per_class} = "
              f"{args.classes * args.methods_per_class} definições < "
              f"{METHOD_IDS_CEIL} — corpus não cruza o teto de method_ids",
              file=sys.stderr)
    plan, artifacts = generate(args.out, args.seed, args.classes,
                               args.methods_per_class, args.strings, args.fields)
    pkg_rel = f"{JAVA_DIR}/{PACKAGE.replace('.', '/')}"
    print(f"[gen-dex-stress] {pkg_rel}/Stress_00001..{args.classes:05d}.java: "
          f"{args.classes} classes x {args.methods_per_class} métodos = "
          f"{args.classes * args.methods_per_class}")
    print(f"[gen-dex-stress] StringPoolStress.java: {args.strings} constantes "
          f"longas únicas; InvokeCustomStress.java: {LAMBDA_COUNT} lambdas + "
          f"{len(METHOD_REF_SITES)} method refs; FieldStress.java: "
          f"{args.fields} campos")
    print(f"[gen-dex-stress] {PLAN_NAME}: expected_method_refs="
          f"{plan['expected_method_refs']} multidex_ways={plan['multidex_ways']}")
    print(f"[gen-dex-stress] OK: {len(artifacts)} arquivos em {args.out} "
          f"(seed={args.seed})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
